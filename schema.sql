-- Dashboard J&T - Capotamento
-- Execute no SQL Editor do Supabase.

create table if not exists public.capotamento_diario (
    id bigint generated by default as identity primary key,
    data date not null,
    nome_regional text,
    codigo_regional bigint,
    uf text,
    nome_base text not null,
    codigo_base bigint not null,

    media_recebidos_7d numeric,
    media_entregues_prazo_7d numeric,
    maior_entrega_prazo_7d numeric,

    retidos_1d numeric,
    indice_1d numeric,
    retidos_3d numeric,
    indice_3d numeric,
    retidos_5d numeric,
    indice_5d numeric,
    retidos_7d numeric,
    indice_7d numeric,
    retidos_10d numeric,
    indice_10d numeric,

    alerta_fonte boolean not null default false,
    capotada_fonte boolean not null default false,
    alerta_calculado boolean not null default false,
    capotada_calculado boolean not null default false,
    divergencia_regra boolean not null default false,

    capotamentos_30d integer not null default 0,
    dias_consecutivos_capotamento integer not null default 0,

    rm text,
    coordenador text,
    supervisor text,
    lider text,
    tipo_base text,
    status_gestao text,

    score_risco numeric not null default 0,
    janela_critica text,
    status_risco text not null default 'NORMAL',
    falta_qtd numeric,
    falta_indice numeric,

    importado_em timestamptz not null default now(),
    constraint capotamento_diario_un unique (data, codigo_base)
);

create index if not exists idx_capotamento_data on public.capotamento_diario(data desc);
create index if not exists idx_capotamento_base on public.capotamento_diario(codigo_base, data desc);
create index if not exists idx_capotamento_status on public.capotamento_diario(data, status_risco);
create index if not exists idx_capotamento_coord on public.capotamento_diario(data, coordenador);
create index if not exists idx_capotamento_sup on public.capotamento_diario(data, supervisor);

alter table public.capotamento_diario enable row level security;

